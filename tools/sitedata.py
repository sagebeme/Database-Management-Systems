#!/usr/bin/env python3
"""Writes site/assets/course.js: the phases, days, extras and guides the course website shows,
read from SYLLABUS.md and the folders. The site is plain static files, so the result is committed.

    python tools/sitedata.py           # write it
    python tools/sitedata.py --check   # fail if it's out of date (CI runs this)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site" / "assets" / "course.js"
REPO = "https://github.com/sagebeme/Database-Management-Systems"
BRANCH = "master"
SKIP = {"__pycache__", ".pytest_cache"}

# The extras sit in the ledger after the day they follow. Each is (after day, kind, title, path).
EXTRAS = [
    (28, "extra", "Predict the Output", "phase-2-many-tables/extra-predict-the-output/README.md"),
    (28, "extra", "The Breach", "phase-2-many-tables/extra-the-breach/README.md"),
    (38, "notes", "Worked examples: design and algebra", "phase-3-design/worked-examples.md"),
    (49, "notes", "Worked examples: normalisation", "phase-4-normalisation/worked-examples.md"),
    (52, "checkpoint", "Checkpoint 2: Practice Test 2", "phase-4-normalisation/checkpoint-2-practice-test-2/README.md"),
    (77, "notes", "Worked examples: transactions and storage", "phase-6-transactions-and-storage/worked-examples.md"),
    (78, "checkpoint", "Checkpoint 3: Practice Test 3", "phase-6-transactions-and-storage/checkpoint-3-practice-test-3/README.md"),
    (90, "notes", "The database landscape", "phase-7-beyond-mysql/the-database-landscape.md"),
]

GUIDES = [
    ("README.md", "About the course and setting up"),
    ("WINDOWS.md", "Doing the course on Windows"),
    ("SYLLABUS.md", "The syllabus"),
]


def starter_files(day: Path) -> list[str]:
    starter = day / "starter"
    files = [p.relative_to(starter).as_posix() for p in sorted(starter.rglob("*"))
             if p.is_file() and not (set(p.relative_to(starter).parts) & SKIP)]
    # The kata goes last, the way the READMEs list it.
    return sorted(files, key=lambda f: (Path(f).stem == "kata", f))


def first_sentence(readme: Path) -> str:
    text = readme.read_text(encoding="utf-8")
    m = re.search(r"^## The brief\s*\n+(.+?)(?:\n\n|$)", text, re.S | re.M)
    if not m:
        return ""
    para = re.sub(r"\s+", " ", m.group(1)).strip()
    sentence = re.split(r"(?<=[.!?])\s", para, maxsplit=1)[0]
    return sentence


def build() -> dict:
    syllabus = (ROOT / "SYLLABUS.md").read_text(encoding="utf-8")
    sections = re.split(r"^## Phase ", syllabus, flags=re.M)[1:]
    phase_dirs = sorted(p for p in ROOT.glob("phase-*") if p.is_dir())
    phases, days = [], []
    for n, (section, folder) in enumerate(zip(sections, phase_dirs), 1):
        title = section.splitlines()[0].split(":", 1)[1].strip()
        learn = re.search(r"^Learn: (.*)$", section, re.M).group(1)
        ends = re.search(r"^Ends with: (.*)$", section, re.M).group(1)
        folders = {int(m.group(1)): p for p in folder.iterdir() if (m := re.match(r"day-(\d{3})-", p.name))}
        numbers = []
        for row in re.finditer(r"^\| (\d+) \| (.+?) \| (.+?) \| \w+ \|$", section, re.M):
            d = int(row.group(1))
            day = folders[d]
            files = starter_files(day)
            days.append({
                "day": d,
                "phase": n,
                "title": row.group(2),
                "teaches": row.group(3),
                "dir": f"{folder.name}/{day.name}",
                "brief": first_sentence(day / "README.md"),
                "files": files,
                "setup": next((s for s in ("setup.sql", "setup.js") if (day / s).is_file()), None),
                "kata": any(Path(f).stem == "kata" for f in files),
            })
            numbers.append(d)
        phases.append({
            "phase": n,
            "title": title,
            "dir": folder.name,
            "learn": learn,
            "ends": ends,
            "first": min(numbers),
            "last": max(numbers),
        })
    extras = []
    for after, kind, title, path in EXTRAS:
        if not (ROOT / path).is_file():
            raise SystemExit(f"missing extra: {path}")
        phase = next(d["phase"] for d in days if d["day"] == after)
        extras.append({"after": after, "phase": phase, "kind": kind, "title": title, "path": path})
    guides = [{"path": p, "title": t} for p, t in GUIDES]
    guides += [{"path": f"{p['dir']}/README.md", "title": f"Phase {p['phase']}: {p['title']}"} for p in phases]
    return {"repo": REPO, "branch": BRANCH, "phases": phases, "days": days, "extras": extras, "guides": guides}


def render(data: dict) -> str:
    body = json.dumps(data, indent=1, ensure_ascii=False)
    return ("// Generated by tools/sitedata.py from SYLLABUS.md and the day folders. Don't edit by hand.\n"
            f"window.DBMS_COURSE = {body};\n")


def main(argv: list[str]) -> int:
    text = render(build())
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("site/assets/course.js is out of date. Run `python tools/sitedata.py` and commit it.")
            return 1
        print("site/assets/course.js is up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    data = json.loads(text.split("=", 1)[1].rstrip(";\n"))
    print(f"Wrote site/assets/course.js: {len(data['days'])} days, {len(data['extras'])} extras.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

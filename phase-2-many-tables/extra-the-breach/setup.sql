-- Extra: The Breach. Soko Safi, an online grocer in Nairobi (made up), and the logs of its staff system.
-- Made by a seeded script, so it never changes. Every name and address here is invented.

CREATE TABLE staff (
    username        VARCHAR(20) PRIMARY KEY,
    name            VARCHAR(40) NOT NULL,
    dept            VARCHAR(20) NOT NULL,
    joined_on       DATE NOT NULL,
    left_on         DATE NULL,              -- their last day; NULL if they still work here
    account_enabled BOOLEAN NOT NULL
);

CREATE TABLE logins (
    id       INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(20) NOT NULL,          -- what was typed, so not always a real account
    ip       VARCHAR(15) NOT NULL,
    at       DATETIME NOT NULL,
    success  BOOLEAN NOT NULL
);

CREATE TABLE exports (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    username   VARCHAR(20) NOT NULL,
    table_name VARCHAR(20) NOT NULL,
    row_count  INT NOT NULL,
    at         DATETIME NOT NULL
);

CREATE TABLE password_resets (
    id        INT AUTO_INCREMENT PRIMARY KEY,
    account   VARCHAR(20) NOT NULL,         -- whose password was reset
    reset_by  VARCHAR(20) NOT NULL,         -- who did it
    at        DATETIME NOT NULL,
    ticket_id INT NULL                      -- the help-desk ticket that asked for it
);

